const DICTS: Record<string, Dict> = { en, hi };

export function t(lang: string, key: keyof typeof en, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] || DICTS.hi;
  let value = dict[key] ?? DICTS.hi[key] ?? DICTS.en[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, String(v));
  return value;
}

export function isValidated(code: string): boolean {
  return LANGUAGES.find((l) => l.code === code)?.validated ?? false;
}

export function isRTL(code: string): boolean {
  return !!LANGUAGES.find((l) => l.code === code)?.rtl;
}

export function applyRTL(code: string) {
  const rtl = isRTL(code);
  if (I18nManager.isRTL !== rtl) {
    try { I18nManager.allowRTL(rtl); I18nManager.forceRTL(rtl); } catch {}
  }
}
